"""Профили каналов контент-завода — всё, чем каналы отличаются, в одном месте.

До 07.09.2026 завод знал ровно один канал. Это было видно не в одном месте,
а в трёх: хэндл приходил из `NEXUS_CHANNEL_HANDLE`, обложку карусели искала
`carousel.cover_photo()` (портрет Веры), а сценарист писал вообще без голоса.
Пока канал был один, это работало.

Каналов стало два, и они не совпадают ни в чём. У «Точки опоры» ведущая в
кадре — портрет и есть обложка. У «Я знаю, почему» ведущая **анонимна**:
её лицо не должно появиться ни на одном слайде, потому что канал ведёт
ИИ-аватар, собранный по образу живого человека, и её имя с лицом мы
защищаем намеренно.

Профиль — это данные, а не поведение. Здесь нет ни одной ветки `if`:
разница между каналами лежит в полях, а код, который их читает, один.

Канал по умолчанию — `tochka`, и это не вкусовщина: так поведение завода
для уже существующего канала не меняется ни на пиксель. Второй канал
включается переменной `NEXUS_CHANNEL`.
"""
from __future__ import annotations

import os
from dataclasses import dataclass

DEFAULT_CHANNEL = "tochka"


@dataclass(frozen=True)
class Channel:
    """Один канал: как он подписывается, как выглядит и каким голосом говорит."""

    id: str
    label: str
    handle: str
    carousel_style: str
    # Показывать ли ведущую на обложке. False — обложка типографская или на
    # сгенерированном фоне, но лица живого человека на ней нет никогда.
    show_presenter: bool
    # Промпт фона обложки для fal.ai. Пусто — фон не генерируем.
    # Модель рисует ТОЛЬКО фон: буквы поверх кладёт Pillow, потому что
    # кириллицу диффузионные модели коверкают всегда (см. carousel.py).
    cover_prompt: str
    # Блок, который подмешивается в промпт сценариста. Пусто — сценарист
    # работает как работал, без голоса канала.
    voice: str


ZNAYU_VOICE = """
Канал «Я знаю, почему»: психология, нейропсихология, отношения, воспитание.
Ведущая обращается к женщине на «ты», как подруга на кухне, а не как эксперт
с кафедры.

Сценарий строится строго в этом порядке:
1) механизм — что в этот момент происходит в мозге или психике;
2) инструмент — ОДИН приём, который можно применить, а не список из пяти;
3) применение — конкретная бытовая сцена: ссора, укладывание, утро понедельника.
Порядок не переставлять. Начав с приёма, получаем обычный совет, а советов в
ленте и без нас достаточно.

Запрещено: ставить диагнозы и обещать лечение; называть имя ведущей; упоминать,
что видео сделано ИИ; обороты «просто отпусти», «полюби себя», «пространство»,
«гармония», «осознанность», «ты не поверишь», «мало кто знает», «топ-5».
Не обвинять зрительницу: «ты не ленивая» — можно, «ты всё делаешь неправильно» —
нельзя.

Числа в тексте для озвучки писать словами: «семь», «двадцать», а не «7» и «20».
Синтез читает цифру то количественным, то порядковым числительным, и на
«двадцать минут» это слышно сразу.
""".strip()


CHANNELS: dict[str, Channel] = {
    "tochka": Channel(
        id="tochka",
        label="Точка опоры",
        handle="",  # исторически приходит из NEXUS_CHANNEL_HANDLE
        carousel_style="beige",
        show_presenter=True,
        cover_prompt="",
        voice="",
    ),
    "znayu": Channel(
        id="znayu",
        label="Я знаю, почему",
        handle="@znayu.pochemu",
        carousel_style="znayu",
        show_presenter=False,
        cover_prompt=(
            "soft cinematic photograph, warm amber and deep plum light, "
            "shallow depth of field, quiet domestic interior at dusk, "
            "no people, no faces, no text, no letters, no watermark, "
            "empty space in the lower third for a caption"
        ),
        voice=ZNAYU_VOICE,
    ),
}


def current() -> Channel:
    """Канал, под который сейчас работает завод.

    Неизвестное имя в переменной — не повод падать: контент-завод обязан
    собирать посты и с опечаткой в настройке. Возвращаем канал по умолчанию,
    то есть ровно прежнее поведение.
    """
    return get(os.getenv("NEXUS_CHANNEL", "").strip())


def get(channel_id: str) -> Channel:
    """Профиль по имени. Пусто или незнакомое имя — канал по умолчанию."""
    return CHANNELS.get((channel_id or "").strip().lower()) or CHANNELS[DEFAULT_CHANNEL]


def handle(channel: Channel | None = None) -> str:
    """Подпись канала в подвале слайда.

    `NEXUS_CHANNEL_HANDLE` продолжает побеждать: на «Точке опоры» хэндл живёт
    в переменной окружения с самого начала, и профиль не должен его затирать.
    У нового канала переменной нет — берётся значение из профиля.
    """
    override = os.getenv("NEXUS_CHANNEL_HANDLE", "").strip()
    if override:
        return override
    return (channel or current()).handle
