"""Продакшн-команда: семь агентов в Telegram, каждый со своей песочницей.

Отдельный пакет, а не правка `backend/services/agent_engine.py`. Тот движок
описывает фоновых работников Nexus OS (Строитель, Библиотекарь, ...) — у него
захардкожены фазы на роль и нет ни файловых инструментов, ни потолка итераций,
ни гейта подтверждения. Ломать его ради новых ролей значит трогать ~600 тестов
ради задачи, которая с ним не связана. Здесь всё новое, старое не тронуто.

Что переиспользуется из backend: `LLMService` (протокол OpenAI/DeepSeek),
`budget` (дневной лимит расходов) и `websearch`. Дублировать их незачем.
"""
from pathlib import Path

from dotenv import load_dotenv

# Строго здесь, до импорта `crew.config`: тот вычисляет пути и потолки на
# уровне модуля, и без загруженного .env взял бы значения по умолчанию.
# Так же поступает `backend/core/config.py` — и по той же причине.
#
# Найдено смоук-проверкой: `crew.bot.allowed_users()` возвращал пустое
# множество при заполненном .env, то есть бот молча не отвечал бы никому.
load_dotenv()

# Токены ботов — в отдельном маленьком файле, а не в общем `.env`.
#
# Причина не в архитектуре, а в том, как это выглядит у человека: в `.env`
# шестьдесят восемь строк, и блок с токенами в самом низу фаундер трижды
# не нашёл, хотя блок был на месте. В файле на двадцать строк не потеряешься.
#
# `override=False` намеренно: если переменная уже задана в окружении или в
# `.env`, она главнее — этот файл только заполняет пустоты.
load_dotenv(Path(__file__).resolve().parent.parent / "crew.env", override=False)

# Доверять хранилищу сертификатов Windows, а не только бандлу `certifi`.
#
# Причина найдена живой проверкой 06.09.2026: на этой машине Avast
# перехватывает TLS и подменяет сертификаты своим корнем
# («Avast Web/Mail Shield Root»). Он лежит в хранилище Windows, поэтому
# curl и браузер работают, а Python — нет: у него свой бандл, и любой
# HTTPS-вызов падает с CERTIFICATE_VERIFY_FAILED. Симптом при этом
# выглядит как «модель недоступна», то есть уводит искать причину не там.
#
# `inject_into_ssl` переключает проверку на системное хранилище — то же
# самое, чему уже доверяет вся остальная машина. Отключать проверку
# сертификатов (`verify=False`) вместо этого нельзя: это сняло бы защиту
# от подмены на всех вызовах, включая платные.
try:
    import truststore

    truststore.inject_into_ssl()
except ImportError:  # pragma: no cover - на чистой машине без перехвата не нужен
    pass
